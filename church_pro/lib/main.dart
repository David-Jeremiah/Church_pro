import 'dart:ui';

import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'app/app.dart';
import 'core/utils/app_messenger.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Hide the red DEBUG ribbon everywhere.
  WidgetsApp.debugAllowBannerOverride = false;

  // 1. Start Firebase. If it fails, show the reason instead of a blank crash.
  try {
    await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  } catch (e) {
    runApp(_StartupError('$e'));
    return;
  }

  // 2. Any unhandled async error (permission denied, no network...) is logged
  //    and shown to the user as a SnackBar.
  PlatformDispatcher.instance.onError = (error, stack) {
    debugPrint('Unhandled error: $error\n$stack');
    showAppError(error);
    return true;
  };

  // 3. Run the app.
  runApp(const ProviderScope(child: ChurchApp()));
}

class _StartupError extends StatelessWidget {
  const _StartupError(this.message);

  final String message;

  @override
  Widget build(BuildContext context) => MaterialApp(
    debugShowCheckedModeBanner: false,
    home: Scaffold(
      body: Center(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: SelectableText('The app could not start.\n\n$message', textAlign: TextAlign.center),
        ),
      ),
    ),
  );
}